# Крок 2. Створіть програму, яка запитує у користувача список чисел. Програма повинна 
# створити словник, де ключі - унікальні значення зі списку, а значення - кількість входжень кожного значення в список.
# Нарешті, програма повинна надрукувати отриманий словник.

numbers = input('Введіть числа через пробіл: ').strip().split()

dict = dict()

for number in numbers:
    if number not in dict:
        dict[number] = 1
    else:
        dict[number] += 1
        
print(dict)