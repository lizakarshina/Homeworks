# Напишіть функцію для сортування списку з об'єктів за певним атрибутом об'єктів.
# Наприклад, у вас є список об'єктів класу "Студент", і ви хочете відсортувати студентів за їхнім середнім балом.

students = [{"Іван": 85}, {"Марія": 92}, {"Олександр": 78}, {"Катерина": 90}]

sorted_students = sorted(students, key=lambda grade: list(grade.values())[0])

print(sorted_students)